# 공공건설임대주택 표준건축비 — 국토교통부고시 제2023-64호 (2023. 2. 1. 전부개정)
#
# 재개발로 지은 임대주택은 도시정비법 제55조에 따라 시·도지사가 인수하는데,
# 그 인수가격이 이 표의 표준건축비다(부속토지는 기부채납). 조합이 받는 임대 인수수입이 된다.
#   임대 인수수입 = 임대 공급면적 × 표준건축비
#
# 표 읽는 법 (고시 원문 주석 그대로)
#   · 행 구분은 "주거전용면적" 기준, 단가는 "주택공급면적"에 곱한다. 둘을 섞지 말 것
#   · 주택공급면적 = 「주택공급에 관한 규칙」 제21조제5항 공급면적 − 그 밖의 공용면적
#     (= 전용 + 주거공용. 지하주차장 등 기타공용은 빠진다 → 우리 engine 의 공급면적과 같은 범위)
#   · 표준건축비에는 부가가치세가 포함되어 있다
#   · 단위는 천원/㎡. engine 은 만원 단위를 쓰므로 조회 함수가 ÷10 해서 돌려준다
#
# 2016년 이후 동결됐다가 2023년에 9.8% 인상된 값이다. 다음 개정 때 이 표를 갱신할 것
#   (재검토기한 : 2023-07-01 기준 매 3년)

#층수 구간 → {전용면적 상한(㎡) : 단가(천원/㎡)}. None 은 "초과" 구간
STANDARD_BUILD_COST_KRW_THOUSAND = {
    "5층 이하":   {40: 1126.7, 50: 1145.2, 60: 1109.5, None: 1120.8},
    "6~10층":    {40: 1209.8, 50: 1226.1, 60: 1188.5, None: 1192.3},
    "11~20층":   {40: 1143.0, 50: 1154.1, 60: 1119.3, None: 1118.8},
    "21층 이상":  {40: 1162.6, 50: 1173.8, 60: 1139.2, None: 1138.4},
}

#노드 슬라이더에 쓰는 순서. o────o────o────o
FLOOR_BANDS = ["5층 이하", "6~10층", "11~20층", "21층 이상"]

#기본값 : 재개발 임대동은 중층으로 짓는 경우가 많다
DEFAULT_FLOOR_BAND = "11~20층"


#표준건축비 (만원/㎡)
#  floor_band          : FLOOR_BANDS 중 하나 (사용자가 노드 슬라이더로 고른다)
#  exclusive_area_m2   : 임대 1세대 주거전용면적. 행을 고르는 데만 쓴다
def standard_build_cost_per_m2(floor_band: str, exclusive_area_m2: float) -> float:
    row = STANDARD_BUILD_COST_KRW_THOUSAND.get(floor_band)
    if row is None:
        raise ValueError(
            f"층수 구간이 올바르지 않습니다: {floor_band} (가능한 값: {', '.join(FLOOR_BANDS)})"
        )

    for upper in (40, 50, 60):
        if exclusive_area_m2 <= upper:
            return row[upper] / 10        # 천원/㎡ → 만원/㎡
    return row[None] / 10


#6~10층이 가장 비싼 이유를 화면에서 설명할 때 쓴다
#  엘리베이터·코어 설비가 들어가기 시작하는데 세대수가 적어 세대당 분담이 커진다.
#  11층 이상이 되면 세대수가 늘어 같은 설비 비용이 희석되어 단가가 다시 내려간다
MOST_EXPENSIVE_BAND = "6~10층"
